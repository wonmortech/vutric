//! Vutric for Flutter apps (`flutter_rust_bridge`). See [`api`] for what the app calls.

// flutter_rust_bridge takes owned arguments (`String`, `Vec<u8>`) by design.
#[allow(clippy::needless_pass_by_value)]
pub mod api;

// The app process's side of the foreign-app adapters (ADR-0066); iOS does not host them yet.
#[cfg(not(target_os = "ios"))]
mod compat_host;

// The `:compat` service process's entry (ADR-0066): called through JNI, outside flutter_rust_bridge.
// Built on every Unix but iOS so the Linux CI checks it; only Android calls it.
#[cfg(all(unix, not(target_os = "ios")))]
mod compat_service;

// Generated by `flutter_rust_bridge_codegen generate` (apps/mobile-spike); never edited by hand.
#[allow(clippy::all, clippy::pedantic, unused_qualifications)]
mod frb_generated;
