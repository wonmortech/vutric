"""Generates lib/design/themes.g.dart from the Claude Design handoff (design/claude-design/Vutric App v4.dc.html).

The handoff keeps its 9 themes as a JS array of 26 CSS values each. Copying them by hand invites typos, so this
script reads them, converts CSS colours and shadows to Flutter values and writes one Dart table.
Run from apps/mobile-spike:  python tool/gen_themes.py
"""

import io
import re
import sys

SRC = '../../design/claude-design/Vutric App v4.dc.html'
OUT = 'lib/design/themes.g.dart'

NAMES = ['bg', 'bgAlt', 'raised', 'ink', 'muted', 'line', 'lineStrong', 'action', 'actionInk', 'accent',
         'accentHi', 'accent2', 'accentInk', 'hero', 'heroInk', 'heroMuted', 'glass', 'glassShadow', 'canvas',
         'ok', 'err', 'font', 'mono', 'rPill', 'rCard', 'rPanel']

CONST = {
    'this.GL': 'inset 0 .5px 0 rgba(255,255,255,.95),inset 0 0 0 .5px rgba(255,255,255,.6),'
               '0 0 0 .5px rgba(0,0,0,.06),0 8px 24px -8px rgba(0,0,0,.16)',
    'this.GD': 'inset 0 .5px 0 rgba(255,255,255,.3),inset 0 0 0 .5px rgba(255,255,255,.14),0 8px 24px -8px rgba(0,0,0,.6)',
    'this.SF': 'system', 'this.SFM': 'mono', 'this.GE': 'geist', 'this.GM': 'mono',
}


# Accessibility corrections on top of the handoff (ADR-0011, decision 14). Every text pair must reach WCAG AA (4.5:1);
# test/pure_test.dart measures all 9 themes. The handoff file itself stays as the designer delivered it.
AA = {
    # White on Apple system blue is 4.0:1 (light) and 3.7:1 (dark). #0071E3 is Apple's own button blue on the web,
    # 4.7:1 with white text.
    ('ios', 'action'): '#0071E3', ('ios', 'accent'): '#0071E3',
    ('ios-dark', 'action'): '#0071E3', ('ios-dark', 'accent'): '#0071E3',
    # secondaryLabel at 60% is 3.3:1 on the grouped background; 76% is 5.0:1.
    ('ios', 'muted'): 'rgba(60,60,67,.76)',
    # White on #F43F6B is 3.6:1; one step deeper in the same pink is 4.7:1.
    ('blush', 'accent'): '#D92B57',
}


def color(css):
    css = css.strip()
    m = re.fullmatch(r'#([0-9a-fA-F]{6})', css)
    if m:
        return 'Color(0xFF%s)' % m.group(1).upper()
    m = re.fullmatch(r'#([0-9a-fA-F]{3})', css)
    if m:
        return 'Color(0xFF%s)' % ''.join(c * 2 for c in m.group(1)).upper()
    m = re.fullmatch(r'rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)', css)
    if m:
        r, g, b, a = int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4))
        return 'Color(0x%02X%02X%02X%02X)' % (round(a * 255), r, g, b)
    raise ValueError('colour: ' + css)


def split_top(s):
    """Splits a CSS shadow list on commas outside parentheses."""
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out if p.strip()]


def px(v):
    return float(v.replace('px', '') or 0)


def shadows(css):
    """Outer shadows become BoxShadow; a 0-blur spread ring becomes the border; inset ones become a highlight."""
    outer, border, highlight = [], None, None
    for part in split_top(css):
        inset = part.startswith('inset')
        part = part.replace('inset', '').strip()
        m = re.match(r'([-\d.]+(?:px)?)\s+([-\d.]+(?:px)?)\s*([-\d.]+(?:px)?)?\s*([-\d.]+(?:px)?)?\s*(.*)$', part)
        x, y, blur, spread, col = m.group(1), m.group(2), m.group(3) or '0', m.group(4) or '0', m.group(5)
        x, y, blur, spread = px(x), px(y), px(blur), px(spread)
        c = color(col)
        if inset:
            if y > 0 and highlight is None:
                highlight = c
            continue
        if x == 0 and y == 0 and blur == 0:
            border = (c, spread)
            continue
        outer.append('BoxShadow(color: %s, offset: Offset(%g, %g), blurRadius: %g, spreadRadius: %g)'
                     % (c, x, y, blur, spread))
    return outer, border, highlight


def main():
    html = io.open(SRC, encoding='utf-8').read()
    rows = re.findall(r"\{ id: '([\w-]+)', name: '([^']+)', tag: '([^']+)', desc: '([^']+)', v: \[(.*?)\] \}", html)
    if len(rows) != 9:
        sys.exit('expected 9 themes, found %d' % len(rows))
    out = ['// GENERATED by tool/gen_themes.py from design/claude-design/Vutric App v4.dc.html. Do not edit by hand.',
           '', "import 'package:flutter/painting.dart';", '', "import 'tokens.dart';", '',
           'const vutricThemes = <VutricTokens>[']
    for tid, name, tag, desc, body in rows:
        vals = [CONST.get(raw, raw.strip('\'"')) for raw in re.findall(r"'[^']*'|\"[^\"]*\"|this\.\w+", body)]
        if len(vals) != 26:
            sys.exit('%s: %d values' % (tid, len(vals)))
        v = dict(zip(NAMES, vals))
        for (aid, key), val in AA.items():
            if aid == tid:
                v[key] = val
        outer, border, highlight = shadows(v['glassShadow'])
        font = v['font']
        family = ('VFont.system' if font == 'system' else 'VFont.geist' if font == 'geist'
                  else 'VFont.mono' if font == 'mono' else 'VFont.serif')
        material = ('VMaterial.brutal' if tid == 'signal' else
                    'VMaterial.outline' if tid in ('paper', 'terminal') else 'VMaterial.glass')
        dark = tid not in ('ios', 'paper', 'blush', 'signal')
        out.append('  VutricTokens(')
        out.append("    id: '%s',\n    name: '%s',\n    tag: '%s',\n    desc: '%s',\n    dark: %s,"
                   % (tid, name, tag, desc, 'true' if dark else 'false'))
        for k in NAMES:
            if k in ('glassShadow', 'font', 'mono', 'rPill', 'rCard', 'rPanel'):
                continue
            out.append('    %s: %s,' % (k, color(v[k])))
        out.append('    glassShadow: [%s],' % ', '.join(outer))
        out.append('    glassBorder: %s,' % (color('rgba(0,0,0,0)') if border is None else border[0]))
        out.append('    glassBorderWidth: %g,' % (0 if border is None else border[1]))
        out.append('    glassHighlight: %s,' % ('null' if highlight is None else highlight))
        out.append('    font: %s,' % family)
        out.append('    material: %s,' % material)
        out.append('    rPill: %g,\n    rCard: %g,\n    rPanel: %g,' % (px(v['rPill']), px(v['rCard']), px(v['rPanel'])))
        out.append('  ),')
    out.append('];')
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT)


main()
